#!/usr/bin/env python3
"""Scan API/app Python imports and write dependency-map.generated.md.

Stdlib only. Run from repo root (TILA/) or anywhere:

  python3 scripts/scan-api-imports.py
"""

from __future__ import annotations

import ast
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "API" / "app"
OUT = ROOT / "docs" / "architecture" / "dependency-map.generated.md"


def module_name(path: Path) -> str:
    rel = path.relative_to(APP).with_suffix("")
    parts = list(rel.parts)
    if parts[-1] == "__init__":
        parts = parts[:-1]
    return "app." + ".".join(parts) if parts else "app"


def top_package(mod: str) -> str:
    parts = mod.split(".")
    if len(parts) >= 2 and parts[0] == "app":
        return ".".join(parts[:2])  # app.ai, app.services, …
    return parts[0]


def iter_imports(path: Path) -> set[str]:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    except SyntaxError:
        return set()
    found: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.startswith("app."):
                    found.add(alias.name)
        elif isinstance(node, ast.ImportFrom):
            if node.module and node.module.startswith("app"):
                found.add(node.module)
    return found


def main() -> None:
    edges: dict[str, set[str]] = defaultdict(set)
    files = sorted(APP.rglob("*.py"))
    for path in files:
        if "__pycache__" in path.parts:
            continue
        src = module_name(path)
        src_pkg = top_package(src)
        for imp in iter_imports(path):
            dst_pkg = top_package(imp)
            if src_pkg != dst_pkg:
                edges[src_pkg].add(dst_pkg)

    lines = [
        "<!-- GENERATED by scripts/scan-api-imports.py — do not edit by hand -->",
        "",
        "# API import edges (generated)",
        "",
        f"Source root: `API/app` ({len(files)} files scanned).",
        "",
        "Edges are package-level (`app.<segment>` → `app.<segment>`).",
        "",
        "| From | To |",
        "|------|----|",
    ]
    for src in sorted(edges):
        for dst in sorted(edges[src]):
            lines.append(f"| `{src}` | `{dst}` |")

    if len(edges) == 0:
        lines.append("| _(none)_ | _(no cross-package app.* imports found)_ |")

    lines.extend(
        [
            "",
            "## How to refresh",
            "",
            "```bash",
            "python3 scripts/scan-api-imports.py",
            "```",
            "",
        ]
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({sum(len(v) for v in edges.values())} edges)")


if __name__ == "__main__":
    main()
